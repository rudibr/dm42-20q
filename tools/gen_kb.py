#!/usr/bin/env python3
"""Builds src/kb_default.h from the data files and reports problems.

Codes (2 bits per cell): 0 = weak no, 1 = yes, 2 = unknown, 3 = definite no.
"""
import sys, os, itertools
sys.path.insert(0, os.path.dirname(__file__))
from questions import QUESTIONS
import data_animals, data_plants, data_things, data_other
from extras import EXTRA

KEYS = [k for k, _ in QUESTIONS]
IDX = {k: i for i, k in enumerate(KEYS)}
assert len(IDX) == len(KEYS), "duplicate question key"
NQ = len(KEYS)

def parse(mod, domain):
    objs, errors = [], []
    for ln in mod.DATA.strip().splitlines():
        if not ln.strip():
            continue
        parts = [p.strip() for p in ln.split("|")]
        if len(parts) != 3:
            errors.append(f"bad line: {ln}"); continue
        name, tpl, toks = parts
        if tpl not in mod.TEMPLATES:
            errors.append(f"{name}: unknown template {tpl}"); continue
        row = [0] * NQ
        def setk(tok, code):
            if tok not in IDX:
                errors.append(f"{name}: unknown key '{tok}'"); return
            row[IDX[tok]] = code
        for t in mod.TEMPLATES[tpl].split():
            if t.startswith("~"): setk(t[1:], 2)
            else: setk(t, 1)
        for t in toks.split():
            if t.endswith("?"):           t = "~" + t[:-1]
            if t.startswith("~"):         setk(t[1:], 2)
            elif t.startswith("-"):       setk(t[1:], 3)
            elif t.startswith("!"):       setk(t[1:], 0)
            else:                         setk(t, 1)
        extra = EXTRA.get(name, "")
        for t in extra.split():
            if t.endswith("?"):           t = "~" + t[:-1]
            if t.startswith("~"):         setk(t[1:], 2)
            elif t.startswith("-"):       setk(t[1:], 3)
            elif t.startswith("!"):       setk(t[1:], 0)
            else:                         setk(t, 1)
        # derived rules
        if domain == "animal" and (row[IDX["fly"]] == 1 or row[IDX["bird"]] == 1) and name != "helicopter":
            if row[IDX["wings"]] == 0: row[IDX["wings"]] = 1
        if tpl == "pers" and row[IDX["male"]] == 0:
            row[IDX["male"]] = 2
        # the category column for this domain is always a firm yes
        row[IDX[domain]] = 1
        for c in ("animal", "plant", "thing", "other"):
            if c != domain and row[IDX[c]] == 0:
                row[IDX[c]] = 3        # firm no unless marked ~
        objs.append((name, row))
    return objs, errors

def main():
    allobjs, errs = [], []
    for mod, dom in ((data_animals, "animal"), (data_plants, "plant"),
                     (data_things, "thing"), (data_other, "other")):
        o, e = parse(mod, dom)
        print(f"{dom:7s}: {len(o)} objects")
        allobjs += o; errs += e
    names = [n for n, _ in allobjs]
    for k in EXTRA:
        if k.strip() and k not in names: errs.append(f"extras: unknown object '{k}'")
    dups = {n for n in names if names.count(n) > 1}
    if dups: errs.append(f"duplicate names: {sorted(dups)}")
    for n in names:
        if len(n.encode()) > 23: errs.append(f"name too long: {n}")
    for k, q in QUESTIONS:
        if len(q.encode()) > 63: errs.append(f"question too long: {q}")
    if errs:
        print("\n".join(errs)); sys.exit(1)

    # close pairs: count columns where one says yes and the other says no
    def dist(a, b):
        return sum(1 for x, y in zip(a, b) if (x == 1 and y in (0, 3)) or (y == 1 and x in (0, 3)))
    close = [(dist(a[1], b[1]), a[0], b[0]) for a, b in itertools.combinations(allobjs, 2)]
    close = sorted(c for c in close if c[0] < 2)
    print(f"questions: {NQ}, total objects: {len(allobjs)}, pairs with <2 differences: {len(close)}")
    for d, a, b in close:
        print(f"  {d}: {a} / {b}")

    # write header
    bpr = (NQ + 3) // 4
    out = ["/* Generated by tools/gen_kb.py - do not edit. */",
           "#ifndef KB_DEFAULT_H", "#define KB_DEFAULT_H", "#include <stdint.h>",
           f"#define DEFAULT_NQ   {NQ}", f"#define DEFAULT_NOBJ {len(allobjs)}",
           f"#define DEFAULT_BPR  {bpr}  /* bytes per object row */", "",
           "static const char * const default_questions[DEFAULT_NQ] = {"]
    out += [f'  "{q}",' for _, q in QUESTIONS]
    out += ["};", "", "/* NUL-separated names */", "static const char default_names[] ="]
    out += [f'  "{n}\\0"' for n in names]
    out += [";", "", "static const uint8_t default_cells[DEFAULT_NOBJ][DEFAULT_BPR] = {"]
    for n, row in allobjs:
        b = []
        for i in range(0, NQ, 4):
            v = 0
            for j in range(4):
                if i + j < NQ: v |= row[i + j] << (2 * j)
            b.append(v)
        out.append("  {" + ",".join(str(x) for x in b) + "},")
    out += ["};", "", "#endif", ""]
    path = os.path.join(os.path.dirname(__file__), "..", "src", "kb_default.h")
    open(path, "w").write("\n".join(out))
    print("wrote", os.path.normpath(path))

main()
